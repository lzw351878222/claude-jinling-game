  // 消除：古筝拨音 + 高八度琉璃泛音，连锁 combo 1..12 沿五声音阶逐级上行（A4 → B6）
  match: (o) => {
    const c = clamp(Math.round(+o.combo || 1), 1, 12), m = pd(2 + c);
    Z(o, 0, m, 0.4 - c * 0.008);
    B(o, 0.004, m + 12, 'glass', 0.05 + c * 0.008, { d: 0.5 + c * 0.03 });
    if (c >= 6) N(o, 0.01, { type: 'highpass', f: 6000, a: 0.01, d: 0.25, vol: 0.012 * c });
  },
  // 下落：很轻的闷"嗒"
  drop: (o) => { T(o, 0, { f: rnd(170, 240), f2: 120, glide: 0.05, a: 0.003, d: 0.07, vol: 0.07 }); },
